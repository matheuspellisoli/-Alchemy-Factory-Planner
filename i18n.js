const languageStorageKey = "alchemy-factory-planner:language";

// Idioma: ?lang= na URL, depois a escolha guardada, depois o idioma do navegador; senão inglês.
function detectLanguage() {
  const fromUrl = new URLSearchParams(window.location.search).get("lang");
  if (LANGUAGES[fromUrl]) {
    try {
      localStorage.setItem(languageStorageKey, fromUrl);
    } catch {
      // sem armazenamento: vale só nesta página
    }
    return fromUrl;
  }
  try {
    const saved = localStorage.getItem(languageStorageKey);
    if (LANGUAGES[saved]) return saved;
  } catch {
    // sem armazenamento: segue para o idioma do navegador
  }
  const browser = (navigator.languages || [navigator.language || ""]).map((lang) => String(lang).slice(0, 2).toLowerCase());
  return browser.find((lang) => LANGUAGES[lang]) || "en";
}

let currentLanguage = detectLanguage();

function t(key, vars = {}) {
  const entry = I18N[currentLanguage]?.[key] ?? I18N.pt[key];
  if (entry === undefined) return key;
  if (typeof entry === "function") return entry(vars);
  return entry.replace(/\{(\w+)\}/g, (match, name) => (vars[name] !== undefined ? vars[name] : match));
}

function currentLocale() {
  return LANGUAGES[currentLanguage].locale;
}

// Aplica as traduções nos elementos fixos do HTML: data-i18n (texto), data-i18n-title,
// data-i18n-aria (aria-label) e data-i18n-placeholder.
function applyStaticTranslations(root = document) {
  document.documentElement.lang = currentLocale();
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-tutorial]").forEach((el) => { el.href = LANGUAGES[currentLanguage].tutorial; });
}

function setLanguage(lang) {
  if (!LANGUAGES[lang]) return;
  currentLanguage = lang;
  try {
    localStorage.setItem(languageStorageKey, lang);
  } catch {
    // a escolha vale só nesta sessão
  }
  // O ?lang= do link já cumpriu o papel; sem ele, recarregar usa a escolha guardada.
  try {
    const url = new URL(window.location.href);
    if (url.searchParams.has("lang")) {
      url.searchParams.delete("lang");
      history.replaceState(null, "", url);
    }
  } catch {
    // sem permissão para mexer na URL
  }
  applyStaticTranslations();
  window.dispatchEvent(new CustomEvent("languagechange-app", { detail: { lang } }));
}
